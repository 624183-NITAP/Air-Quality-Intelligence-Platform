import type { LocationData } from '../types';
import { calculateIndianNAQI, pm25ToUSEPAAQI } from '../utils/airCalculators';

function createReferenceLocation(params: {
  id: string;
  city: string;
  region: string;
  country: string;
  latitude: number;
  longitude: number;
  pm25: number;
  pm10: number;
  no2: number;
  so2: number;
  co: number;
  ozone: number;
  temperatureC: number;
  humidityPct: number;
  windSpeedKmh: number;
  windDirectionCompass: string;
  boundaryLayerHeightMeters: number;
  inversionCondition: LocationData['weather']['inversionCondition'];
  dispersionFactor: LocationData['weather']['dispersionFactor'];
  visibilityKm: number;
  smogAlertTitle: string;
  smogAlertDescription: string;
  primarySources: string[];
}): LocationData {
  const indianNAQI = calculateIndianNAQI({
    pm25: params.pm25,
    pm10: params.pm10,
    no2: params.no2,
    so2: params.so2,
    co: params.co,
  });
  const usEPAAQI = pm25ToUSEPAAQI(params.pm25);

  return {
    id: params.id,
    city: params.city,
    region: params.region,
    country: params.country,
    latitude: params.latitude,
    longitude: params.longitude,
    sourceType: 'historical_reference',
    dataSourceName: 'CPCB / Copernicus Atmospheric Historical Seasonal Baseline',
    dataTimestamp: '2026-11-20T08:00:00Z',
    pollutants: {
      pm25: params.pm25,
      pm10: params.pm10,
      no2: params.no2,
      so2: params.so2,
      co: params.co,
      ozone: params.ozone,
    },
    weather: {
      temperatureC: params.temperatureC,
      humidityPct: params.humidityPct,
      windSpeedKmh: params.windSpeedKmh,
      windDirectionDeg: 315,
      windDirectionCompass: params.windDirectionCompass,
      surfacePressureHpa: 1014,
      boundaryLayerHeightMeters: params.boundaryLayerHeightMeters,
      visibilityKm: params.visibilityKm,
      inversionCondition: params.inversionCondition,
      dispersionFactor: params.dispersionFactor,
      dataSource: 'IMD / Reanalysis Baseline',
      isRealtime: false,
      observationTimeISO: '2026-11-20T08:00:00Z',
    },
    calculatedAQI: {
      indianNAQI,
      usEPAAQI,
    },
    smogAlertTitle: params.smogAlertTitle,
    smogAlertDescription: params.smogAlertDescription,
    primarySources: params.primarySources,
  };
}

